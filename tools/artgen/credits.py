"""credits: write and check assets/yearofice/credits.json (Art spec, The credits file).

Every file under assets/yearofice/{geo,animations,textures,models} gets exactly one entry. Generated
files list their recipe or species file; found-based files carry the found asset's provenance from
art-src/found/<asset>/source.json and its licence file.
Usage: python3 -I tools/artgen/credits.py [write|check]"""
import json, os, sys, glob, hashlib

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
ASSETS = os.path.join(ROOT, "src", "main", "resources", "assets", "yearofice")
sys.path.insert(0, os.path.join(HERE, "..", "modelgen"))
import modelgen  # noqa: E402

ALLOWED = {"project", "CC0-1.0", "CC-BY-3.0", "CC-BY-4.0", "CC-BY-SA-3.0", "CC-BY-SA-4.0", "CC-BY-NC-4.0", "CC-BY-NC-SA-4.0",
           "MIT", "BSD-2-Clause", "BSD-3-Clause", "Zlib", "OFL-1.1", "permission"}
BLOCKER = {"CC-BY-SA-3.0", "CC-BY-SA-4.0", "CC-BY-NC-4.0", "CC-BY-NC-SA-4.0"}  # RECONCILE 151: personal use only
COVERED = ("geo", "animations", "textures", "models", "blockstates", "sounds")


def rel(p):
    return os.path.relpath(p, os.path.join(ROOT, "src", "main", "resources")).replace(os.sep, "/")


def found(asset):
    return json.load(open(os.path.join(ROOT, "art-src", "found", asset, "source.json")))


def found_entry(asset_id, src, files, changes, extra=None):
    e = {"asset_id": asset_id, "files": files, "source_type": src["source_type"], "title": src["title"],
         "author": src["author"], "licence": src["licence"], "licence_file": src["licence_file"], "retrieved": src["retrieved"],
         "source": src.get("pack_page"), "mirror": src.get("mirror_repo") or src.get("download"),
         "mirror_commit": src.get("mirror_commit"), "changes": changes, "release_blocker": src["licence"] in BLOCKER}
    if src["licence"] not in ("CC0-1.0", "project"):
        e["credit_line"] = f"{src['title']} by {src['author']}, {src['licence']}"
    e.update(extra or {})
    return {k: v for k, v in e.items() if v is not None}


def build():
    entries = []
    # item icons
    for fn in sorted(glob.glob(os.path.join(HERE, "recipes", "item", "*.json"))):
        r = json.load(open(fn))
        name = r["id"].split(":")[1]
        folder = r.get("folder", "item")
        files = [f"assets/yearofice/textures/{folder}/{name}.png"] + [f"assets/yearofice/textures/{folder}/{name}_{v}.png" for v in r.get("variants", {})]
        if folder == "item":
            files.append(f"assets/yearofice/models/item/{name}.json")
        recipe = os.path.relpath(fn, ROOT)
        if r["kind"] == "found_icon":
            src = found(r["found"])
            sp = os.path.relpath(os.path.join(ROOT, r["source"]), os.path.join(ROOT, "art-src", "found", r["found"]))
            entries.append(found_entry(f"tex_{name}", src, files,
                                       "Recoloured colour by colour onto palette ramp steps, re-outlined in #1a1512" + (", edited (see recipe)" if r.get("edits") else "") + (", decay variants by ramp remap" if r.get("variants") else ""),
                                       {"recipe": recipe, "original": r["source"], "original_sha256": src["files"][sp], "generator_version": "artgen 0.4.0"}))
        else:
            entries.append({"asset_id": f"tex_{name}", "files": files, "source_type": "generated", "recipe": recipe,
                            "licence": "project", "generator_version": "artgen 0.4.0", "release_blocker": False})
    # models
    seen = set()
    for sid in modelgen.all_species():
        p = modelgen.load_species(sid)
        aid = p.get("anim_id", p["geo_id"])
        files = []
        geo = f"assets/yearofice/geo/entity/{p['geo_id']}.geo.json"
        for f in (geo, f"assets/yearofice/animations/entity/{aid}.animation.json"):
            if f not in seen:
                files.append(f)
                seen.add(f)
        for also in p.get("anim_copies", []):
            f = f"assets/yearofice/animations/entity/{also}.animation.json"
            if f not in seen:
                files.append(f)
                seen.add(f)
        for var in p["textures"]:
            f = f"assets/yearofice/textures/entity/{p['texture_dir']}/{var}.png"
            if f not in seen:
                files.append(f)
                seen.add(f)
        if not files:
            continue
        sf = f"tools/modelgen/species/{sid}.json"
        base = p.get("base")
        if base:
            src = found(base)
            entries.append(found_entry(f"model_{sid}", src, files,
                                       "Proportion reference only: measured by tools/modelgen/import_glb.py into art-src/found/" + base +
                                       "/measure.json; the cube model, texture and animations are generated by modelgen from the species file",
                                       {"species_file": sf, "original_sha256": src["original_sha256"], "generator_version": modelgen.VERSION}))
        else:
            entries.append({"asset_id": f"model_{sid}", "files": files, "source_type": "generated", "recipe": sf,
                            "licence": "project", "generator_version": modelgen.VERSION, "release_blocker": False})
    # generated block models and blockstates
    import fire_ring  # noqa: E402
    entries.append({"asset_id": "model_fire_ring", "files": fire_ring.outputs(), "source_type": "generated",
                    "recipe": "tools/artgen/fire_ring.py", "licence": "project", "generator_version": fire_ring.VERSION,
                    "release_blocker": False})
    # block textures from recipes/block, one entry per block
    for fn in sorted(glob.glob(os.path.join(HERE, "recipes", "block", "*.json"))):
        r = json.load(open(fn))
        name = r["id"].split(":")[1]
        files = [f"assets/yearofice/textures/block/{name}_{face}.png" for face in r["faces"]]
        files = [f for f in files if os.path.isfile(os.path.join(ROOT, "src", "main", "resources", f))]
        if files:
            entries.append({"asset_id": f"tex_block_{name}", "files": files, "source_type": "generated", "recipe": os.path.relpath(fn, ROOT),
                            "licence": "project", "generator_version": "artgen 0.4.0", "release_blocker": False})
    # world block models and blockstates (M2)
    import world_blocks  # noqa: E402
    entries.append({"asset_id": "model_world_blocks", "files": world_blocks.outputs(), "source_type": "generated",
                    "recipe": "tools/artgen/world_blocks.py", "licence": "project", "generator_version": world_blocks.VERSION,
                    "release_blocker": False})
    import snare  # noqa: E402
    entries.append({"asset_id": "model_snare", "files": snare.outputs(), "source_type": "generated",
                    "recipe": "tools/artgen/snare.py", "licence": "project", "generator_version": snare.VERSION,
                    "release_blocker": False})
    # synthesized sounds: one entry per soundgen recipe whose files are shipped
    for fn in sorted(glob.glob(os.path.join(ROOT, "tools", "soundgen", "recipes", "**", "*.json"), recursive=True)):
        r = json.load(open(fn))
        base = r["id"].split(":")[1].replace(".", "/")
        n = r.get("variants", 1)
        files = [f"assets/yearofice/sounds/{base}{i + 1 if n > 1 else ''}.ogg" for i in range(n)]
        files = [f for f in files if os.path.isfile(os.path.join(ROOT, "src", "main", "resources", f))]
        if files:
            entries.append({"asset_id": "snd_" + r["id"].split(":")[1].replace(".", "_"), "files": files, "source_type": "generated",
                            "recipe": os.path.relpath(fn, ROOT), "licence": "project", "generator_version": "soundgen 0.1.0",
                            "release_blocker": False})
    return {"schema": 1, "note": "One entry per shipped art file. Generated entries name their recipe; found entries name source, licence file and the original's SHA-256.", "entries": entries}


def check(doc):
    errs = []
    listed = {}
    for e in doc["entries"]:
        if e["licence"] not in ALLOWED:
            errs.append(f"{e['asset_id']}: licence {e['licence']} not allowed")
        if e["source_type"] != "generated":
            lf = os.path.join(ROOT, e.get("licence_file", ""))
            if not os.path.isfile(lf):
                errs.append(f"{e['asset_id']}: licence file missing")
            if e["licence"].startswith("CC-BY") and not e.get("credit_line"):
                errs.append(f"{e['asset_id']}: CC-BY without credit line")
            if e["licence"] in BLOCKER and not e.get("release_blocker"):
                errs.append(f"{e['asset_id']}: SA/NC asset not marked release_blocker")
        for f in e["files"]:
            if f in listed:
                errs.append(f"{f}: listed twice")
            listed[f] = e["asset_id"]
            if not os.path.isfile(os.path.join(ROOT, "src", "main", "resources", f)):
                errs.append(f"{f}: listed but missing")
    for kind in COVERED:
        for p in glob.glob(os.path.join(ASSETS, kind, "**", "*.*"), recursive=True):
            if rel(p) not in listed:
                errs.append(f"{rel(p)}: no credits entry")
    if glob.glob(os.path.join(ROOT, "src", "main", "resources", "assets", "minecraft", "**", "*.*"), recursive=True):
        errs.append("files under assets/minecraft/")
    return errs


if __name__ == "__main__":
    cmd = (sys.argv[1:] or ["write"])[0]
    path = os.path.join(ASSETS, "credits.json")
    if cmd == "write":
        json.dump(build(), open(path, "w"), indent=1)
    doc = json.load(open(path))
    errs = check(doc)
    print("\n".join(errs) or f"credits PASS: {len(doc['entries'])} entries, {sum(len(e['files']) for e in doc['entries'])} files")
    sys.exit(1 if errs else 0)
